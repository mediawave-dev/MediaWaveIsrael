/**
 * Copy the Horizon logo's path data, verbatim, from logos/horizon/*.svg into
 * src/components/ui/logo-paths.ts (DECISIONS #52). Nothing is redrawn: every `d`, every
 * transform and every viewBox comes from the design files. Colours are not copied; the
 * component paints through --logo-a, --logo-b and --logo-tag.
 * Run after the design files change: node scripts/build-logo-paths.mjs
 */
import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(ROOT, 'logos/horizon')
const VARIANTS = ['horizontal', 'compact', 'stacked', 'mark']

/** Parts in file order (the same in every variant): the disc's two halves, then the name. */
const PART_NAMES = ['mark-a', 'mark-b', 'media', 'drop', 'wave', 'tag', 'rules']

/** Walk the SVG: paths keep their class (a | b | t | l), own transform and the enclosing <g> transform. */
function parse(svg) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1]
  const parts = []
  let group = null
  const re = /<g transform="([^"]+)">|<\/g>|<path ([^>]*?)\/>/g
  let m
  while ((m = re.exec(svg))) {
    if (m[1] !== undefined) { group = m[1]; continue }
    if (m[0] === '</g>') { group = null; continue }
    const attrs = m[2]
    const cls = (attrs.match(/class="([^"]+)"/) || [])[1]
    const d = attrs.match(/ d="([^"]+)"/)?.[1] ?? attrs.match(/^d="([^"]+)"/)?.[1]
    const transform = (attrs.match(/transform="([^"]+)"/) || [])[1]
    if (!cls || !d) throw new Error(`unexpected path: ${attrs.slice(0, 80)}`)
    parts.push({ part: PART_NAMES[parts.length], role: cls, d, ...(transform ? { transform } : {}), ...(group && group !== 'translate(0 0)' ? { group } : {}) })
  }
  return { viewBox, parts }
}

const out = {}
for (const v of VARIANTS) out[v] = parse(readFileSync(resolve(SRC, `mediawave-${v}-dark.svg`), 'utf8'))

const ts = `// GENERATED by scripts/build-logo-paths.mjs from logos/horizon/mediawave-<variant>-dark.svg.
// Do not edit by hand: the geometry and the space between the mark and the name are the
// design (brand rules). Roles: a = Media and the upper half, b = Wave, the drop on the i and
// the lower half, t = the tagline, l = the tagline's rules. Parts name each path for motion.

export type LogoRole = 'a' | 'b' | 't' | 'l'
export type LogoPartName = 'mark-a' | 'mark-b' | 'media' | 'drop' | 'wave' | 'tag' | 'rules'
export interface LogoPart { part: LogoPartName; role: LogoRole; d: string; transform?: string; group?: string }
export interface LogoArt { viewBox: string; parts: LogoPart[] }

export const LOGO_ART: Record<'horizontal' | 'compact' | 'stacked' | 'mark', LogoArt> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(resolve(ROOT, 'src/components/ui/logo-paths.ts'), ts)
for (const v of VARIANTS) console.log(`${v.padEnd(11)} ${out[v].viewBox.padEnd(22)} ${out[v].parts.map((p) => p.role).join('')}`)
