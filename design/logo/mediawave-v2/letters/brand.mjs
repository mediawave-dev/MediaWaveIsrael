// Writes src/sun/brand-art.ts: the MediaWave name in its drawn letters (option 1, Nati's pick of 13.11.2026), in pieces,
// so the header can draw it and the footer can fold it into the MW mark.
//   node brand.mjs <path/to/brand-art.ts>
// One coordinate space with the picked MW file: cap height 150, baseline y 305, x-height 112, every letter leaned 36 across 150.
// M and W are the picked file's, point for point. The W and the letters after it are given in the W's own place (as in the
// MW mark), and the word moves them right by `wx`.
import fs from 'fs'
import { M, W_LOCAL, LEAN, BASE, X, E_LOW, A_LOW, D_LOW, I_LOW, V_LOW, place, drop } from './glyphs.mjs'
const f = (n) => +n.toFixed(2)
const g = 9
let x = 232 + g
let edia = place(E_LOW, x); x += E_LOW.w + g
edia += place(D_LOW, x); x += D_LOW.w + g
const ix = x; edia += place(I_LOW, x); x += I_LOW.w + g
edia += place(A_LOW, x); x += A_LOW.w
const mediaEnd = x                                   // the a's right edge on the baseline
const wx = x + 40 - 242                              // the W's foot stands 40 after the a
let u = 386 + g                                      // in the W's own place
let ave = place(A_LOW, u); u += A_LOW.w + 5
ave += place(V_LOW, u); u += 110
ave += place(E_LOW, u); u += E_LOW.w
const aveEnd = u                                     // the e's right edge on the baseline, W's place
const dr = drop(ix, X)
const disc = { cx: -30, cy: BASE - 75, d: 166 }      // beside the name, centred on the capitals
const top = 130, bottom = BASE + 10, left = disc.cx - disc.d / 2 - 2, right = wx + aveEnd + LEAN * X + 4
const WORD = {
  viewBox: [f(left), top, f(right - left), bottom - top],
  lean: f(LEAN), base: BASE, xh: X, wx: f(wx),
  disc, M, W: W_LOCAL, edia, ave, drop: dr,
  grad: { a: [88, 155, f(mediaEnd), 305], b: [232, 155, f(aveEnd + LEAN * X), 305] },
  // the footer folds each run of small letters toward a line inside its capital's last stroke (upright x on the baseline)
  fold: { edia: { u0: 214, right: f(mediaEnd) }, ave: { u0: 368, right: f(aveEnd) } },
}
const out = process.argv[2]
const src = `// MediaWave, the name in its drawn letters (Nati's pick 1, 13.11.2026): the M and W of the MW logo he picked, point for point,
// and the small letters drawn as the same leaning blocks with sharp wedge cuts. Generated by
// design/logo/mediawave-v2/letters/brand.mjs; do not edit by hand.
// One space with the MW mark (emblem-art.ts): cap height 150, baseline y 305, x-height 112. The W and the letters after it
// are in the W's own place (as in the MW mark); in the name they stand \`wx\` further right.
export const WORD = ${JSON.stringify(WORD, null, 2)} as const
`
if (out) fs.writeFileSync(out, src)
console.log(JSON.stringify({ viewBox: WORD.viewBox, wx: WORD.wx, mediaEnd: f(mediaEnd), aveEnd: f(aveEnd), ratio: f((right - left) / (bottom - top)), discRight: disc.cx + disc.d / 2 }))
