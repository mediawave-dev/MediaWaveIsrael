// Writes src/sun/emblem-open.ts: the header's logo (Horizon, compact) taken apart for the footer mark's open state (D268):
// its M and W alone, the runs "edia" and "ave", the drop, the disc, each with its offset and its measured box, in the
// compact logo's own coordinates. The boxes are measured by a browser (getBBox), so they are exact.
//   node design/logo/mediawave-v2/letters/open-art.mjs
import { createRequire } from 'module'
import fs from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..')
const require = createRequire(resolve(ROOT, 'package.json'))
const puppeteer = require('puppeteer')
const ts = fs.readFileSync(resolve(ROOT, 'src/components/ui/logo-paths.ts'), 'utf8')
const ART = Function('return ' + ts.slice(ts.indexOf('= {') + 2).replace(/;?\s*$/, ''))()
const C = ART.compact.parts, part = (p) => C.find((x) => x.part === p)
const off = (p) => { let x = 0; for (const t of [p.group, p.transform]) { const m = /translate\(([-\d.]+)/.exec(t || ''); if (m) x += +m[1] } return x }
const first = (d) => d.slice(0, d.indexOf('Z') + 1), rest = (d) => d.slice(d.indexOf('Z') + 1)
const media = part('media'), wave = part('wave'), drop = part('drop'), ma = part('mark-a'), mb = part('mark-b')
const pieces = { M: [first(media.d), off(media)], edia: [rest(media.d), off(media)], W: [first(wave.d), off(wave)], ave: [rest(wave.d), off(wave)], drop: [drop.d, off(drop)], discA: [ma.d, off(ma)], discB: [mb.d, off(mb)] }
const b = await puppeteer.launch({ headless: 'new' }); const pg = await b.newPage()
await pg.setContent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ART.compact.viewBox}">${Object.entries(pieces).map(([k, [d, x]]) => `<path id="${k}" transform="translate(${x} 0)" d="${d}"/>`).join('')}</svg>`)
const boxes = await pg.evaluate((keys) => Object.fromEntries(keys.map((k) => { const el = document.getElementById(k), bb = el.getBBox(), x = +el.getAttribute('transform').match(/translate\(([-\d.]+)/)[1]; return [k, [+(bb.x + x).toFixed(2), +bb.y.toFixed(2), +(bb.x + x + bb.width).toFixed(2), +(bb.y + bb.height).toFixed(2)]] })), Object.keys(pieces))
await b.close()
const out = {}
for (const [k, [d, x]] of Object.entries(pieces)) out[k] = { d, x, box: boxes[k] }
const disc = { cx: +((boxes.discA[0] + boxes.discA[2]) / 2).toFixed(2), cy: +((boxes.discA[1] + boxes.discB[3]) / 2).toFixed(2), d: +(boxes.discB[3] - boxes.discA[1]).toFixed(2) }
fs.writeFileSync(resolve(ROOT, 'src/sun/emblem-open.ts'), `// The header's logo (Horizon, compact) taken apart for the footer mark's open state (D268). Generated by
// design/logo/mediawave-v2/letters/open-art.mjs from src/components/ui/logo-paths.ts; do not edit by hand.
// Coordinates of the compact logo: baseline y 0, cap height about 70. Each piece is drawn at translate(x 0); box is
// [x0, y0, x1, y1] with that offset included.
export const OPEN = ${JSON.stringify({ ...out, disc }, null, 2)} as const
`)
console.log(JSON.stringify({ boxes, disc }))
